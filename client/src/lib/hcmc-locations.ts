export function findHcmcDistrict(
  districtCode: number | null | undefined,
  districtName?: string | null,
): HcmcDistrict | undefined {
  if (districtCode != null) {
    const byCode = HCMC_DISTRICTS.find((d) => d.code === districtCode);
    if (byCode) return byCode;
  }

  if (!districtName) return undefined;
  const normalized = districtName.trim().toLowerCase();
  return HCMC_DISTRICTS.find((d) => {
    const name = d.name.toLowerCase();
    return (
      name === normalized ||
      normalized.includes(name) ||
      name.includes(normalized)
    );
  });
}

export function getHcmcWards(
  districtCode: number | null | undefined,
  districtName?: string | null,
): string[] {
  return findHcmcDistrict(districtCode, districtName)?.wards ?? [];
}

export function getHcmcStreets(
  districtCode: number | null | undefined,
  districtName?: string | null,
): string[] {
  return findHcmcDistrict(districtCode, districtName)?.streets ?? [];
}
